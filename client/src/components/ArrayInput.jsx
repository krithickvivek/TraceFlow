/**
 * @file ArrayInput.jsx
 * @description Input component for entering a custom comma-separated array or
 *              generating a random one. Validates length, range, and format
 *              before dispatching to the global trace state.
 * @exports ArrayInput (default)
 */

import { useState } from 'react';
import { useTrace, ActionTypes } from '../context/TraceContext';
import { Shuffle } from 'lucide-react';

/** Minimum number of elements allowed. */
const MIN_LENGTH = 2;

/** Maximum number of elements allowed. */
const MAX_LENGTH = 20;

/** Minimum allowed integer value. */
const MIN_VALUE = -999;

/** Maximum allowed integer value. */
const MAX_VALUE = 9999;

/** Number of random elements generated by the Randomize button. */
const RANDOM_COUNT = 8;

/** Upper bound (exclusive) for random values. */
const RANDOM_MAX = 99;

/**
 * Validate a raw comma-separated string and return parsed integers or an error.
 *
 * @param {string} raw - User input string.
 * @returns {{ values: number[]|null, error: string|null }}
 */
function parseInput(raw) {
  const trimmed = raw.trim();
  if (!trimmed) return { values: null, error: 'Please enter at least 2 numbers.' };

  const tokens = trimmed.split(',').map((t) => t.trim());

  const values = [];
  for (const token of tokens) {
    if (token === '') continue;
    if (!/^-?\d+$/.test(token)) {
      return { values: null, error: `"${token}" is not a valid integer.` };
    }
    const num = Number(token);
    if (num < MIN_VALUE || num > MAX_VALUE) {
      return { values: null, error: `Values must be between ${MIN_VALUE} and ${MAX_VALUE}.` };
    }
    values.push(num);
  }

  if (values.length < MIN_LENGTH) {
    return { values: null, error: `Enter at least ${MIN_LENGTH} numbers.` };
  }
  if (values.length > MAX_LENGTH) {
    return { values: null, error: `Maximum ${MAX_LENGTH} numbers allowed.` };
  }

  return { values, error: null };
}

/**
 * Array input component with validation and a randomize button.
 *
 * @returns {JSX.Element}
 */
export default function ArrayInput() {
  const { state, dispatch } = useTrace();
  const [text, setText] = useState(state.inputArray.join(', '));
  const [error, setError] = useState(null);

  /**
   * Validate and submit the current text input.
   */
  const handleSubmit = () => {
    const { values, error: err } = parseInput(text);
    if (err) {
      setError(err);
      return;
    }
    setError(null);
    dispatch({ type: ActionTypes.SET_INPUT, payload: values });
    dispatch({ type: ActionTypes.GENERATE_STEPS });
  };

  /**
   * Handle Enter key to submit.
   * @param {React.KeyboardEvent} e
   */
  const handleKeyDown = (e) => {
    if (e.key === 'Enter') handleSubmit();
  };

  /**
   * Generate random integers and auto-submit.
   */
  const handleRandomize = () => {
    const values = Array.from({ length: RANDOM_COUNT }, () =>
      Math.floor(Math.random() * RANDOM_MAX) + 1
    );
    setText(values.join(', '));
    setError(null);
    dispatch({ type: ActionTypes.SET_INPUT, payload: values });
    dispatch({ type: ActionTypes.GENERATE_STEPS });
  };

  return (
    <div className="space-y-2">
      <label htmlFor="array-input" className="block text-sm font-medium text-[var(--color-text)]">
        Input Array
      </label>

      <div className="flex gap-2">
        <input
          id="array-input"
          type="text"
          value={text}
          onChange={(e) => setText(e.target.value)}
          onKeyDown={handleKeyDown}
          placeholder="e.g. 5, 3, 8, 1, 2"
          className="flex-1 bg-[var(--color-bg)] border border-[var(--color-border)] rounded-lg px-3 py-2
                     text-sm text-[var(--color-text)] placeholder:text-[var(--color-text-muted)]
                     focus-accent"
        />
        <button
          onClick={handleRandomize}
          className="flex items-center gap-1 px-3 py-2 rounded-lg border border-[var(--color-border)]
                     text-[var(--color-accent)] transition-colors text-sm focus-accent"
          style={{ '--hover-bg': 'var(--color-btn-subtle-hover)' }}
          onMouseEnter={(e) => { e.currentTarget.style.backgroundColor = 'var(--color-btn-subtle-hover)'; }}
          onMouseLeave={(e) => { e.currentTarget.style.backgroundColor = ''; }}
          title="Randomize array"
          aria-label="Randomize array"
        >
          <Shuffle size={14} />
          Random
        </button>
      </div>

      <button
        onClick={handleSubmit}
        className="w-full py-2 rounded-lg bg-[var(--color-accent)] text-white font-medium text-sm
                   hover:opacity-90 transition-colors focus-accent"
      >
        Generate Steps
      </button>

      {error && (
        <p className="text-red-500 text-xs mt-1" role="alert">
          {error}
        </p>
      )}
    </div>
  );
}
